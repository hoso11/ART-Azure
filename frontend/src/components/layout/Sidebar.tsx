interface SidebarProps {
  role: string;
  className?: string;
  onNavigate?: () => void;
}

export function Sidebar({ role, className, onNavigate }: SidebarProps) {
  const pathname = usePathname();
  const nav = role === "admin" ? adminNav : userNav;

  return (
    <aside className={cn("w-64 bg-brand-900 text-white min-h-screen flex flex-col", className)}>
      <div className="px-6 py-5 border-b border-brand-700">
        <Link href="/" className="text-xl font-bold tracking-tight" onClick={onNavigate}>
          ART Մանուֆակտուրա
        </Link>
      </div>

      <nav className="flex-1 px-3 py-4 space-y-1">
        {nav.map((item) => {
          const active = pathname === item.href || (item.href !== "/dashboard" && pathname.startsWith(item.href));
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={onNavigate}
              className={cn(
                "flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors",
                active
                  ? "bg-brand-700 text-white"
                  : "text-brand-200 hover:bg-brand-800 hover:text-white"
              )}
            >
              <span className="h-5 w-5">{item.icon}</span>
              {item.label}
            </Link>
          );
        })}
      </nav>

      <div className="px-6 py-4 border-t border-brand-700 text-xs text-brand-400">
        ART Մանուֆակտուրա v1.0
      </div>
    </aside>
  );
}

